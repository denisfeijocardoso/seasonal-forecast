def _to_float_palette(palette: RgbIntPalette) -> RgbPalette:
    converted = {}
    for color_id, (red, green, blue) in palette.items():
        value = (red, green, blue)
        if _DEFAULT_INT_COLORS.get(color_id) == value:
            converted[color_id] = _DEFAULT_FLOAT_COLORS[color_id]
        else:
            converted[color_id] = (red / 255.0, green / 255.0, blue / 255.0)
    return converted


def forecast_palette() -> RgbPalette:
    return _to_float_palette(_FORECAST_GRADS_RGB_INT)


def verification_palette(file_names: Iterable[str] | None = None) -> RgbPalette:
    names = tuple(file_names) if file_names is not None else ("crgb2.gs",)
    if names not in _VERIFICATION_PALETTES:
        joined = ", ".join(names) or "<empty>"
        raise ValueError(f"Paleta de verificacao congelada nao cadastrada: {joined}")
    return _to_float_palette(_VERIFICATION_PALETTES[names])
